CREATE OR REPLACE FUNCTION public.my_employee_organisation()
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO ''
AS $function$
  SELECT jsonb_build_object(
    'department_code',org.id,
    'department',org.name,
    'subdepartment_code',dep.department_code,
    'subdepartment',dep.name,
    'position_code',p.position_code,
    'position_title',p.position_title,
    'designation_code',ds.designation_code,
    'designation',ds.title
  )
  FROM public.employee_accounts a
  JOIN public.employee_records e ON e.id=a.employee_id
  LEFT JOIN public.position_records p ON p.id=e.position_id
  LEFT JOIN public.departments dep ON dep.id=p.department_id
  LEFT JOIN public.organisation_departments org ON org.id=dep.parent_department_id
  LEFT JOIN public.designations ds ON ds.id=p.designation_id
  WHERE a.user_id=auth.uid()
    AND a.is_active
    AND NOT a.must_change_password
    AND e.employment_state<>'inactive'
$function$;
REVOKE ALL ON FUNCTION public.my_employee_organisation() FROM public,anon,authenticated;
